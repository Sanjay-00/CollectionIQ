def test_risk_columns_are_shaded_red_never_green(data):
    c, p = data
    m = build_report(c, p, "2026-08", "2026-07", "Regional")
    for b in m["blocks"]:
        if b["type"] != "table":
            continue
        for row in render._cell_colors(b):
            for bg, _ in row:
                assert bg is None or bg.lower() not in ("#16a34a", "#dcfce7", "#f0fdf4")


def test_ai_numbers_must_come_from_the_facts():
    facts = "- 388 new defaulters: 11.9% of last month's STD loans, ₹17.75 Cr SOH."
    assert numbers_check("388 loans fell behind, 11.9% of STD loans.", facts) == []
    assert numbers_check("About 400 loans fell behind.", facts) == ["400"]


def test_ai_paragraph_is_dropped_when_it_invents_a_number(data):
    c, p = data
    m = build_report(c, p, "2026-08", "2026-07", "Leadership")
    good, msg = polish(m, call=lambda prompt: "11 loans that were paid up last month are now behind.")
    assert good and msg.startswith("AI summary added")
    bad, msg = polish(m, call=lambda prompt: "About 9999 loans fell behind.")
    assert bad is None and "9999" in msg
    m["ai_summary"] = good
    assert "AI wording by Gemini" in render.to_html(m)


def test_every_optional_section_builds_and_lands_in_the_annex(data):
    from report_agent.story import OPTIONAL_SECTIONS
    c, p = data
    m = build_report(c, p, "2026-08", "2026-07", "Regional", extras=list(OPTIONAL_SECTIONS))
    base = build_report(c, p, "2026-08", "2026-07", "Regional")
    assert len(m["blocks"]) >= len(base["blocks"])                      # extras only add
    assert _headings(m)[-1] == "Definitions"                            # definitions stay last
    render.to_pdf(m)                                                    # every block renders
    wb = load_workbook(BytesIO(render.to_excel(m)))
    assert len(wb.sheetnames) == len(set(wb.sheetnames))


def test_names_are_escaped_in_html(data):
    c, p = data
    c = c.assign(Unit=c["Unit"].replace("MALEGAON", "R&B <MOTORS>"))
    html = render.to_html(build_report(c, p, "2026-08", "2026-07", "Regional"))
    assert "R&amp;B &lt;MOTORS&gt;" in html and "<MOTORS>" not in html


def test_branch_packs_zip_one_report_per_branch(data):
    import zipfile
    from report_agent.packs import build_branch_packs
    c, p = data
    seen = []
    blob, done = build_branch_packs(c, p, "2026-08", "2026-07", progress=lambda i, n, b: seen.append((i, n, b)))
    names = sorted(zipfile.ZipFile(BytesIO(blob)).namelist())
    assert done == ["BARAMATI", "MALEGAON"] and len(seen) == 2
    assert names == ["BARAMATI_2026-08.pdf", "BARAMATI_2026-08.xlsx", "MALEGAON_2026-08.pdf", "MALEGAON_2026-08.xlsx"]
    blob, _ = build_branch_packs(c, p, "2026-08", "2026-07", with_excel=False)
    assert all(n.endswith(".pdf") for n in zipfile.ZipFile(BytesIO(blob)).namelist())
