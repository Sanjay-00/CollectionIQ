def _headings(model):
    return [b["text"] for b in model["blocks"] if b["type"] == "heading"]


def test_presets_tell_the_same_story_at_different_depths(data):
    c, p = data
    reg = _headings(build_report(c, p, "2026-08", "2026-07", "Regional"))
    lead = _headings(build_report(c, p, "2026-08", "2026-07", "Leadership"))
    assert reg[:3] == lead[:3] == ["Summary", "Scoreboard", "Early Warning: Loans That Slipped"]
    assert "Branches" in reg and "Branches" not in lead            # leaders get the short version
    assert reg[-1] == lead[-1] == "Definitions"


def test_branch_report_needs_one_branch(data):
    c, p = data
    with pytest.raises(ValueError):
        build_report(c, p, "2026-08", "2026-07", "Branch", {"Branch": "All"})
    m = build_report(c[c["Unit"] == "MALEGAON"], p[p["Unit"] == "MALEGAON"], "2026-08", "2026-07", "Branch",
                     {"Branch": "MALEGAON"})
    assert "Executives" in _headings(m) and "Call Lists" in _headings(m)


def test_percent_kpis_change_in_points(data):
    from utils import compute_metrics
    c, p = data
    m = build_report(c, p, "2026-08", "2026-07", "Leadership")
    kpi = next(it for b in m["blocks"] if b["type"] == "kpis" for it in b["items"] if it["label"] == "Delinquency %")
    now, before = compute_metrics(c, p)["Delinquency %"][0], compute_metrics(p, p.iloc[0:0])["Delinquency %"][0]
    assert kpi["value"] == f"{now:.2f}%"
    assert kpi["change"] == f"▲ {now - before:.2f} pts" and kpi["worse"] is True


def test_html_pdf_excel_all_carry_the_same_report(data):
    c, p = data
    m = build_report(c, p, "2026-08", "2026-07", "Regional")
    html = render.to_html(m)
    assert "11 new defaulters" in html and "Generated by CollectionIQ" in html
    assert "Gemini" not in html                                   # AI off by default: no AI credit
    pdf = render.to_pdf(m)
    assert pdf[:4] == b"%PDF" and len(pdf) > 5_000
    wb = load_workbook(BytesIO(render.to_excel(m)))
    assert wb.sheetnames[0] == "Summary"
    assert {"Regions", "Branches", "Definitions"} <= set(wb.sheetnames)
    assert any(name.startswith("Call 1") for name in wb.sheetnames)  # call lists with proof columns


def test_tables_are_complete_in_the_annex_even_when_cut_on_the_page(monkeypatch, data):
    import report_agent.story as story
    monkeypatch.setattr(story, "TABLE_ROWS_ON_PAGE", 1)
